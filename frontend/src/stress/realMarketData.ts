/**
 * REAL MARKET DATA — captured, not invented.
 *
 * Every number in this file was downloaded from Yahoo Finance's v8 chart API and
 * the Frankfurter FX service (the ECB's published reference rates) on 30 August
 * 2026, for the window 3 June 2019 → 28 August 2026. Nothing is modelled and
 * nothing is smoothed: these are the closes that actually printed, the dividends
 * that were actually declared, the splits that actually happened and the rates
 * the ECB actually published.
 *
 * ─── THE ONE TRANSFORMATION, AND WHY IT IS NEEDED ────────────────────────────
 *
 * Yahoo's `close` series is RETROACTIVELY SPLIT-ADJUSTED. Apple's close on
 * 3 June 2019 comes back as 43.325, not the 173.30 that printed on the tape,
 * because Yahoo divides all pre-split history by the 4:1 split of 31 August
 * 2020. An investor who bought that day paid 173.30 a share, and their cost base
 * is 173.30 a share forever — so `PRICES` below holds the AS-TRADED close,
 * recovered by multiplying each adjusted close by the cumulative ratio of every
 * split that came after it. The reconstruction is checked in the suite against
 * the two closes either side of each real split.
 *
 * The same is true of dividends, and it matters more, because it is silent:
 * Apple's February 2016 dividend is served as 0.13 when 0.52 a share was paid.
 * Each dividend below therefore carries BOTH figures — `feedAmount` exactly as
 * Yahoo serves it, and `asDeclared`, what the registry actually paid — so a test
 * can show what happens when the feed's number is used as if it were the
 * registry's.
 *
 * `feedCurrency` is likewise Yahoo's own, unedited: the London listing really
 * does come back as "GBp", and it really is quoted in PENCE.
 *
 * SOURCES, so any figure here can be checked against the original:
 *   prices/dividends/splits
 *     https://query1.finance.yahoo.com/v8/finance/chart/<symbol>
 *       ?period1=1451606400&period2=1788000000&interval=1d&events=div|split
 *   FX  https://api.frankfurter.app/2019-01-01..2026-08-30?from=AUD&to=USD,GBP,EUR,JPY
 */

export interface RealDividend {
  date: string;
  /** Exactly what Yahoo's chart events feed serves — split-adjusted. */
  feedAmount: number;
  /** What the registry actually paid per share on the day. */
  asDeclared: number;
}

