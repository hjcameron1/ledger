/** Units of `ccy` per one AUD on `day` — the rate an Australian investor's
 *  broker would have applied. `AUD` is 1 by definition. */
export function audTo(day: string, ccy: string): number {
  if (ccy === 'AUD') return 1;
  const row = FX[day];
  if (!row) throw new Error(`no FX captured for ${day}`);
  const r = (row as unknown as Record<string, number>)[ccy];
  if (!r) throw new Error(`no ${ccy} rate captured for ${day}`);
  return r;
}

/** AUD per one unit of `ccy` on `day` — the direction a holding is converted in. */
export function toAud(day: string, ccy: string): number {
  return 1 / audTo(day, ccy);
}

/** As-traded close in the feed's own currency. Throws rather than guessing. */
export function priceOn(symbol: string, day: string): number {
  const p = PRICES[symbol]?.[day];
  if (p == null) throw new Error(`no captured close for ${symbol} on ${day}`);
  return p;
}

/** Cumulative split ratio applied strictly after `day`. */
export function splitFactorAfter(symbol: string, day: string): number {
  return (SPLITS[symbol] ?? []).reduce((f, s) => (s.date > day ? f * s.ratio : f), 1);
}
